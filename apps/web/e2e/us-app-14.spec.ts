// US-APP-14 · Secrets, for real (serial): masked with a "secret" badge, revealed on request (audited) and hidden again;
// a generated one is read only; hidden settings wait for "Show advanced".
import { expect, test } from '@playwright/test';
import { installAndOpen, useSettingsDemo } from './app-settings';

useSettingsDemo();

test('US-APP-14 secrets are masked until revealed', async ({ page, request }, info) => {
  test.skip(info.project.name !== 'serial', 'Installs an app');
  test.setTimeout(300_000);
  await installAndOpen(page, request, 'Configuration');
  const field = page.getByLabel('Value of MAIL_PASSWORD');
  await expect(field).toHaveAttribute('type', 'password');
  await expect(field).toHaveValue('');
  await expect(page.getByText('secret', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Show MAIL_PASSWORD' }).click();
  await expect(field).toHaveValue('mail-pass');
  await page.getByRole('button', { name: 'Hide MAIL_PASSWORD' }).click();
  await expect(field).toHaveValue('');

  await expect(page.getByLabel('Value of API_TOKEN')).toHaveCount(0);
  await page.getByRole('button', { name: 'Show advanced' }).click();
  const token = page.getByLabel('Value of API_TOKEN');
  await expect(token).toHaveAttribute('readonly', '');
  await expect(page.getByText('Generated by hlabs')).toBeVisible();
  await page.getByRole('button', { name: 'Show API_TOKEN' }).click();
  await expect(token).toHaveValue(/^[A-Za-z0-9_-]{43}$/);
});
